/**
 * Curated Japanese & Korean name corpora pairing each native-script name with
 * its conventional romanization.
 *
 * Why a corpus instead of transliteration:
 *  - Japanese given/family names use special readings (nanori) that a generic
 *    unidecode-style transliterator gets wrong (e.g. 秀雄 → "Hideo", not the
 *    Chinese reading "Xiuxiong"). There is no reading data attached to the
 *    faker kanji corpus, and bundling a full morphological dictionary
 *    (kuromoji, ~15 MB) is far too heavy for a browser extension.
 *  - Korean personal names use conventional romanizations (김 → "Kim", not the
 *    strict Revised-Romanization "Gim").
 *
 * So we pair native script ↔ romaji directly. `s` = native string (kanji /
 * hangul), `r` = romanized form (Hepburn / conventional). Names are displayed
 * in native script; the romaji drives realistic emails/usernames.
 */
export interface ScriptName {
  s: string;
  r: string;
}

export interface NameCorpus {
  surnames: ScriptName[];
  male: ScriptName[];
  female: ScriptName[];
}

